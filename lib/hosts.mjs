// hosts 文件读写（带自己的标记段，可精确回滚）。
//
// 实测结论：本机 hosts 的 ACL 是 Everyone:FullControl，标准用户就能写 ——
// 这正是 Watt Toolkit / Steamcommunity_302 能免 UAC 生效的根本原因。
//
// 但 hosts 只是「把流量引导到我们端口」的手段；真正决定接管与否的是 SNI（见 sni.mjs）。
// 更要紧的是：**必须能干净回滚**。写坏了用户上不了网，这个锅不能背。

import fs from 'node:fs/promises';
import path from 'node:path';

const HOSTS_PATH = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'drivers', 'etc', 'hosts');
const START = '# >>> DSH Accelerator Start >>>';
const END = '# <<< DSH Accelerator End <<<';

// 别家加速器的归因靠 detectConflicts 里的逐行判定（Watt 有包裹段、302 的行尾带 `#S302`），
// 不再维护「标记段」清单 —— 实测 302 重写 hosts 时并不写包裹标记。

const READONLY_HINT = 'hosts 对当前用户不可写（Users 只有 RX）。两条修复路径任选其一：'
  + '① 以管理员身份运行 DSH；'
  + '② 用管理员权限执行 icacls "C:\\Windows\\System32\\drivers\\etc\\hosts" /grant Users:F'
  + '（Steamcommunity_302 等会重写 hosts 的加速器可能把它再改回去）。';

export async function readHosts() {
  try { return await fs.readFile(HOSTS_PATH, 'utf8'); } catch { return ''; }
}

/**
 * hosts 现在能不能写。
 *
 * 实测教训：这台机器上 hosts 的 ACL 曾经是 `Everyone:FullControl`（这正是两类加速器能免 UAC
 * 生效的原因），但 Steamcommunity_302 重写 hosts 后 ACL 变成
 * `SYSTEM:F / Administrators:F / Users:(RX)` —— 标准用户只剩读，`open(...,'r+')` 直接 EPERM。
 * 所以「能不能写」必须在运行期探测，不能当成常量。
 */
export async function probeHostsWritable() {
  try {
    const fh = await fs.open(HOSTS_PATH, 'r+');
    await fh.close();
    return true;
  } catch {
    return false;
  }
}

/** 我们段里缺了哪些受管域名（别家加速器重写 hosts 时会把重叠行删掉）。 */
export function missingManaged(hostsText, hosts) {
  const own = parseOwnBlock(hostsText);
  const present = new Set(own.entries.map((e) => e.host.toLowerCase()));
  return hosts.filter((h) => !present.has(String(h).toLowerCase()));
}

/** 剥掉我们自己的标记段（幂等：没写过也安全）。 */
export function stripOwnBlock(text) {
  const i = text.indexOf(START);
  if (i < 0) return text;
  const j = text.indexOf(END);
  if (j < 0) return text.slice(0, i);           // 只有开头没有结尾，视为损坏块，砍到开头为止
  return text.slice(0, i) + text.slice(j + END.length);
}

/** 生成我们自己的标记段。 */
export function buildOwnBlock(hosts, targetIp) {
  const lines = [START, `# generated by dsh-accelerator — 删除本段即可完全还原`, `# target: ${targetIp}`];
  for (const h of hosts) lines.push(`${targetIp} ${h}`);
  lines.push(END);
  return lines.join('\r\n') + '\r\n';
}

/**
 * 把 hosts 指向 targetIp。返回 {ok, changed, warnings}。
 *
 * ★ 关键：Windows 解析 hosts **取首个命中**，所以我们的段必须排在别家加速器（Steamcommunity_302
 * 会把 800+ 行 `#S302` 写在文件顶部）**之前**，否则「写进去了」和「生效了」是两件事 ——
 * 实测就踩过：我们的 9 条落在第 880 行，302 的第 12 行先命中，加速实际没生效，
 * 而 `parseOwnBlock` 还显示 entries:9/missing:[] 一切正常。
 *
 * @param {string[]} hosts
 * @param {string} targetIp
 */
export async function applyHosts(hosts, targetIp) {
  const original = await readHosts();
  const { text: next, warnings, insertAt } = composeHosts(original, hosts, targetIp);
  if (next === original) return { ok: true, changed: false, warnings, insertedAt: insertAt };
  try {
    await fs.writeFile(HOSTS_PATH, next, 'utf8');
  } catch (e) {
    // 把裸 EPERM 换成可执行的说明 —— 管理页直接显示这句，用户不用猜。
    const err = new Error(e?.code === 'EPERM' || e?.code === 'EACCES' ? READONLY_HINT : String(e?.message ?? e));
    err.code = e?.code ?? 'HOSTS_WRITE_FAILED';
    err.hostsReadonly = e?.code === 'EPERM' || e?.code === 'EACCES';
    throw err;
  }
  return { ok: true, changed: true, warnings, insertedAt: insertAt };
}

/**
 * 纯函数：算出「应用我们这段之后」的 hosts 全文（不碰磁盘，便于离线自检）。
 * 返回 `{text, warnings, insertAt}`；`insertAt >= 0` 表示我们的段被插到了第 insertAt 行之前。
 */
export function composeHosts(original, hosts, targetIp) {
  const cleaned = stripOwnBlock(original);
  const wanted = new Set((hosts ?? []).map((h) => String(h).toLowerCase()));
  const cleanedLines = cleaned.split(/\r?\n/);
  const insertAt = findInsertLine(cleanedLines, wanted);          // -1 = 无冲突，追加到末尾
  const warnings = detectConflicts(original, hosts, { ownAt: insertAt });
  const block = buildOwnBlock(hosts, targetIp);

  let next;
  if (insertAt < 0) {
    const sep = cleaned.endsWith('\n') || cleaned.length === 0 ? '' : '\r\n';
    next = cleaned + sep + block;
  } else {
    const lineStarts = [0];
    for (let i = 0; i < cleaned.length; i += 1) if (cleaned[i] === '\n') lineStarts.push(i + 1);
    const offset = lineStarts[insertAt] ?? cleaned.length;
    next = cleaned.slice(0, offset) + block + cleaned.slice(offset);
  }
  return { text: next, warnings, insertAt };
}

/**
 * 我们的段应该插到第几行**之前**（保证首个命中是我们）。
 * 返回 -1 表示没有任何别家加速器的映射行与我们重叠 → 追加到末尾即可。
 *
 * 命中条件二选一：① 该行映射的域名里有我们受管的；② 该行属于别家加速器
 * （`#S302` 标记，或落在 `# Steam++ Start/End` 段内）。
 */
function findInsertLine(lines, wanted) {
  let inWatt = false;
  for (let i = 0; i < lines.length; i += 1) {
    const t = lines[i].trim();
    if (t.includes('# Steam++ Start')) { inWatt = true; continue; }
    if (t.includes('# Steam++ End')) { inWatt = false; continue; }
    const m = /^(\d+\.\d+\.\d+\.\d+)\s+([^#]+)/.exec(t);
    if (!m) continue;
    const names = m[2].trim().toLowerCase().split(/\s+/).map((n) => n.replace(/\.$/, ''));
    const hitsOurs = names.some((n) => wanted.has(n));
    const foreign = /#S302\b/i.test(t) || inWatt;
    if (hitsOurs || foreign) return i;
  }
  return -1;
}

/** 还原 hosts（只删自己的段，绝不动别人写的）。 */
export async function revertHosts() {
  const original = await readHosts();
  const next = stripOwnBlock(original);
  if (next === original) return { ok: true, changed: false };
  try {
    await fs.writeFile(HOSTS_PATH, next, 'utf8');
  } catch (e) {
    const err = new Error(e?.code === 'EPERM' || e?.code === 'EACCES' ? READONLY_HINT : String(e?.message ?? e));
    err.code = e?.code ?? 'HOSTS_WRITE_FAILED';
    err.hostsReadonly = e?.code === 'EPERM' || e?.code === 'EACCES';
    throw err;
  }
  return { ok: true, changed: true };
}

/**
 * 检查是否有别家加速器的段覆盖了同一批域名。
 *
 * ★ 关键修正：Windows 解析 hosts **取首个命中**，所以「重叠」不等于「打架」——
 * 谁在文件里靠前谁生效，靠后的那份**完全不生效**。所以这里必须算清楚：
 *   - `shadowed`   ：别家的行在我们前面 → **我们的 hosts 引导对这批域名不生效**（severity: blocked）
 *   - `overridden` ：别家的行在我们后面 → 我们优先命中，不影响加速（severity: info）
 * 旧版本无论顺序一律报「会同时生效并互相干扰」，既不符合事实（重叠行只有一条能生效），
 * 也掩盖了真正的问题（我们被压在后面时其实是没生效）。
 *
 * @param {string} hostsText
 * @param {string[]} hosts 受管域名
 * @param {{ownAt?: number}} [opts] ownAt：我们的段**将要**插到第几行之前（applyHosts 写盘前用它预判）
 */
export function detectConflicts(hostsText, hosts, opts = {}) {
  const wanted = new Set((hosts ?? []).map((h) => String(h).toLowerCase()));
  if (wanted.size === 0) return [];
  const lines = hostsText.split(/\r?\n/);

  // 我们自己的段按**行号**排除，而不是靠文本匹配 —— 302 会把重叠行删掉、还会把自己的
  // 868 行插进来，靠字符串切片容易误判。
  const startIdx = lines.findIndex((l) => l.includes(START));
  const endIdx = startIdx < 0 ? -1 : lines.findIndex((l, i) => i > startIdx && l.includes(END));
  const ownFrom = startIdx < 0 ? -1 : startIdx;
  const ownTo = startIdx < 0 ? -1 : (endIdx < 0 ? lines.length - 1 : endIdx);
  // 判定「谁先命中」的基准行：有段就用段首，没有段就用即将插入的位置
  const ownAt = typeof opts.ownAt === 'number' && opts.ownAt >= 0
    ? opts.ownAt
    : (ownFrom >= 0 ? ownFrom : -1);

  // Watt 的包裹段用于归因（它的行不带后缀标记）
  const wattFrom = lines.findIndex((l) => l.includes('# Steam++ Start'));
  const wattTo = wattFrom < 0 ? -1 : lines.findIndex((l, i) => i > wattFrom && l.includes('# Steam++ End'));

  const bySource = new Map();
  for (let i = 0; i < lines.length; i += 1) {
    if (ownFrom >= 0 && i >= ownFrom && i <= ownTo) continue;
    const t = lines[i].trim();
    if (!t || t.startsWith('#')) continue;
    const m = /^(\d+\.\d+\.\d+\.\d+)\s+([^#]+)/.exec(t);
    if (!m) continue;
    const ip = m[1];
    const names = m[2].trim().split(/\s+/);
    let source = 'hosts 里的其它来源';
    if (/#S302\b/i.test(t)) source = 'Steamcommunity_302';
    else if (wattFrom >= 0 && wattTo > wattFrom && i > wattFrom && i < wattTo) source = 'Steam++ (Watt Toolkit)';
    for (const n of names) {
      const host = n.toLowerCase().replace(/\.$/, '');
      if (!wanted.has(host)) continue;
      const rec = bySource.get(source) ?? {
        domains: new Set(), shadowed: new Set(), overridden: new Set(),
        sample: { line: i + 1, ip, host },
      };
      rec.domains.add(host);
      if (ownAt < 0 || i < ownAt) rec.shadowed.add(host);
      else rec.overridden.add(host);
      bySource.set(source, rec);
    }
  }

  const warnings = [];
  for (const [source, rec] of bySource) {
    const domains = [...rec.domains].sort();
    const shadowed = [...rec.shadowed].sort();
    const overridden = [...rec.overridden].sort();
    const n = domains.length;
    const blocked = shadowed.length > 0;
    const message = blocked
      ? `${source} 在第 ${rec.sample.line} 行把 ${n} 个受管域名指向 ${rec.sample.ip}，`
        + `**排在我们的段之前**（Windows 取首个命中）→ 我们的 hosts 引导对这 ${n} 个域名不生效。`
        + `点「启动加速」会把本插件的段插到它前面，让 ${shadowed.length} 个域名优先命中 127.0.0.2。`
      : `${source} 也在 hosts 里管这 ${n} 个受管域名（第 ${rec.sample.line} 行起），`
        + `但排在我们的段之后 → 我们优先命中，不影响加速（它自己独有的域名照常由它处理）。`;
    warnings.push({
      source,
      domains,
      shadowed,
      overridden,
      severity: blocked ? 'blocked' : 'info',
      ip: rec.sample.ip,
      line: rec.sample.line,
      message,
    });
  }
  return warnings;
}

/** 当前我们的段里有哪些域名（给管理页展示「实际生效」）。 */
export function parseOwnBlock(hostsText) {
  const i = hostsText.indexOf(START);
  if (i < 0) return { active: false, entries: [] };
  const j = hostsText.indexOf(END, i);
  const block = hostsText.slice(i, j < 0 ? hostsText.length : j);
  const entries = [];
  for (const line of block.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const [ip, ...names] = t.split(/\s+/);
    for (const n of names) entries.push({ ip, host: n });
  }
  return { active: true, entries };
}

export const HOSTS_FILE = HOSTS_PATH;
